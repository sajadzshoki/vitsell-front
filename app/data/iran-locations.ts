export function getProvinceOptions(t: (key: string) => string) {
  return states(t).map(item => item.key)
}

export function getCitiesForProvince(province: string) {
  if (!province) return []
  return citiesByProvince[province] ?? [province]
}

export function isKnownProvince(province: string) {
  return province in citiesByProvince
}
